#!/usr/bin/env node
// Builds supabase/migrations/<stamp>_schools_data.sql from two French open datasets (Licence Ouverte Etalab):
//   - Annuaire de l'éducation (data.education.gouv.fr, fr-en-annuaire-education): lycées
//   - Principaux établissements d'enseignement supérieur (data.enseignementsup-recherche.gouv.fr)
// Usage: node scripts/build-schools-migration.mjs <lycees.json> <sup.json> <out.sql>
// The JSON files come from the "exports/json" endpoint of each dataset (see docs/SCHOOLS.md).
import { readFileSync, writeFileSync } from "node:fs";

const [lyceesPath, supPath, outPath] = process.argv.slice(2);
if (!lyceesPath || !supPath || !outPath) {
  console.error("Usage: node scripts/build-schools-migration.mjs <lycees.json> <sup.json> <out.sql>");
  process.exit(1);
}

/** Lowercase, no accents, single spaces: the same normalisation is applied to the user's query (src/modules/profile/domain/schools.ts). */
const normalize = (s) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
const clean = (v) => (typeof v === "string" ? v.replace(/\s+/g, " ").trim() : "");
const sql = (v) => (v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const rows = new Map();
for (const l of JSON.parse(readFileSync(lyceesPath, "utf8"))) {
  if (l.etat !== "OUVERT" || !l.identifiant_de_l_etablissement) continue;
  const professional = l.voie_professionnelle === "1" && l.voie_generale !== "1" && l.voie_technologique !== "1";
  rows.set(l.identifiant_de_l_etablissement, {
    id: l.identifiant_de_l_etablissement,
    name: clean(l.nom_etablissement),
    kind: professional ? "lycee_pro" : "lycee",
    isPublic: l.statut_public_prive === "Public",
    city: clean(l.nom_commune),
    postalCode: clean(l.code_postal),
    department: clean(l.libelle_departement),
    extra: "",
  });
}
for (const s of JSON.parse(readFileSync(supPath, "utf8"))) {
  if (!s.uai || rows.has(s.uai)) continue;
  rows.set(s.uai, {
    id: s.uai,
    name: clean(s.uo_lib),
    kind: (s.type_d_etablissement ?? []).includes("Université") ? "universite" : "ecole",
    isPublic: s.secteur_d_etablissement === "public",
    city: clean(s.com_nom),
    postalCode: "",
    department: clean(s.dep_nom),
    extra: clean(s.sigle),
  });
}

const list = [...rows.values()].filter((r) => r.name).sort((a, b) => a.id.localeCompare(b.id));
const values = list.map((r) => {
  const search = normalize([r.name, r.extra, r.city, r.postalCode, r.department].join(" "));
  return `(${[r.id, r.name, r.kind, r.isPublic ? "true" : "false", r.city, r.postalCode, r.department, search]
    .map((v, i) => (i === 3 ? v : sql(v === "" ? null : v)))
    .join(", ")})`;
});

const out = [
  "-- Generated by scripts/build-schools-migration.mjs. Do not edit by hand.",
  "-- Sources (Licence Ouverte Etalab 2.0): Annuaire de l'éducation (Ministère de l'Éducation nationale)",
  "-- and Principaux établissements d'enseignement supérieur (Ministère de l'Enseignement supérieur).",
  `-- ${list.length} schools.`,
  "",
];
for (let i = 0; i < values.length; i += 500) {
  out.push(
    "insert into public.schools (id, name, kind, is_public, city, postal_code, department, search) values",
    values.slice(i, i + 500).join(",\n"),
    "on conflict (id) do nothing;",
    "",
  );
}
writeFileSync(outPath, out.join("\n"));
const counts = {};
for (const r of list) counts[r.kind] = (counts[r.kind] ?? 0) + 1;
console.log(list.length, "schools", counts);
